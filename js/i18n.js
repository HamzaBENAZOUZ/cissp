const LS_LANG = "cissp-lang";
function initialLang() {
  try { const v = localStorage.getItem(LS_LANG); if (v === "fr" || v === "en") return v; } catch { /* ignore */ }
  return "en";   // anglais par défaut ; le bouton FR/EN en haut change la langue (choix mémorisé)
}
let lang = initialLang();
document.documentElement.lang = lang;

export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  document.documentElement.lang = l;
  try { localStorage.setItem(LS_LANG, l); } catch { /* ignore */ }
}
export function t(key, vars = {}, l = lang) {
  const s = DICT[l][key] ?? DICT.fr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
export const locale = () => (lang === "fr" ? "fr-FR" : "en-GB");
